package com.autorize.filter;

import burp.api.montoya.MontoyaApi;
import burp.api.montoya.core.ToolSource;
import burp.api.montoya.core.ToolType;
import burp.api.montoya.http.message.HttpHeader;
import burp.api.montoya.http.message.requests.HttpRequest;
import burp.api.montoya.http.message.responses.HttpResponse;
import com.autorize.model.InterceptionFilter;
import com.autorize.model.UserProfile;
import com.autorize.persistence.PersistenceManager;

import java.util.List;

public class FilterPipeline {

    private final MontoyaApi api;
    private final PersistenceManager persistenceManager;

    public FilterPipeline(MontoyaApi api, PersistenceManager persistenceManager) {
        this.api = api;
        this.persistenceManager = persistenceManager;
    }

    public boolean shouldProcess(HttpRequest request, HttpResponse response, ToolSource toolSource) {
        if (!persistenceManager.isInterceptEnabled()) {
            return false;
        }

        if (response == null) {
            return false;
        }

        // Tool source filtering & extension self-loop prevention
        if (toolSource != null) {
            if (persistenceManager.isIgnoreExtensions() &&
                    toolSource.isFromTool(ToolType.EXTENSIONS, ToolType.SCANNER)) {
                return false;
            }
            if (toolSource.isFromTool(ToolType.PROXY) && !persistenceManager.isInterceptProxy()) {
                return false;
            }
            if (toolSource.isFromTool(ToolType.REPEATER) && !persistenceManager.isInterceptRepeater()) {
                return false;
            }
        }

        // Loop prevention: ensure request was not generated by Autorize itself
        if (isRequestFromAutorize(request)) {
            return false;
        }

        // Status 304/204 check
        if (persistenceManager.isIgnore304()) {
            int code = response.statusCode();
            if (code == 304 || code == 204) {
                return false;
            }
        }

        // Evaluate Interception Filters
        List<InterceptionFilter> filters = persistenceManager.getInterceptionFilters();
        for (InterceptionFilter filter : filters) {
            if (!filter.isEnabled()) continue;
            if (!passesFilter(request, response, filter)) {
                return false;
            }
        }

        return true;
    }

    public boolean shouldProcess(HttpRequest request, HttpResponse response) {
        return shouldProcess(request, response, null);
    }

    private boolean passesFilter(HttpRequest request, HttpResponse response, InterceptionFilter filter) {
        String url = request.url();
        String content = filter.getContent() != null ? filter.getContent() : "";

        switch (filter.getType()) {
            case SCOPE_ONLY:
                return api.scope().isInScope(url);

            case URL_CONTAINS_STRING:
                return url.contains(content);

            case URL_NOT_CONTAINS_STRING:
                return !url.contains(content);

            case URL_CONTAINS_REGEX:
                return filter.getCompiledPattern().matcher(url).find();

            case URL_NOT_CONTAINS_REGEX:
                return !filter.getCompiledPattern().matcher(url).find();

            case REQUEST_BODY_CONTAINS:
                return request.bodyToString().contains(content);

            case RESPONSE_BODY_CONTAINS:
                return response.bodyToString().contains(content);

            case REQUEST_HEADER_CONTAINS:
                return request.headers().stream().anyMatch(h -> h.toString().contains(content));

            case RESPONSE_HEADER_CONTAINS:
                return response.headers().stream().anyMatch(h -> h.toString().contains(content));

            case ONLY_METHODS:
                return matchesAnyMethod(request.method(), content);

            case IGNORE_METHODS:
                return !matchesAnyMethod(request.method(), content);

            case IGNORE_OPTIONS:
                return !request.method().equalsIgnoreCase("OPTIONS");

            default:
                return true;
        }
    }

    private boolean matchesAnyMethod(String requestMethod, String methodList) {
        for (String m : methodList.split("\n")) {
            if (m.trim().equalsIgnoreCase(requestMethod)) {
                return true;
            }
        }
        return false;
    }

    private boolean isRequestFromAutorize(HttpRequest request) {
        for (UserProfile user : persistenceManager.getUserProfiles()) {
            for (String line : user.getHeadersText().split("\n")) {
                int colon = line.indexOf(':');
                if (colon > 0) {
                    String hName = line.substring(0, colon).trim();
                    String hVal = line.substring(colon + 1).trim();
                    if (!hVal.isEmpty() && request.hasHeader(HttpHeader.httpHeader(hName, hVal))) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    public HttpRequest apply304Prevention(HttpRequest request) {
        if (!persistenceManager.isPrevent304()) {
            return request;
        }
        return request.withRemovedHeader("If-None-Match")
                .withRemovedHeader("If-Modified-Since");
    }
}
